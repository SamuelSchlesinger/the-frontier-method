#!/usr/bin/env python3
"""Reproduce the paper's finite Gaussian median-layout illustration.

The mathematics follows Frontier/Layouts/Kernel.lean, Gaussian.lean, and Median.lean.
Computation and --check use only the Python standard library; rendering also needs Matplotlib.
The seed is fixed before sampling. There is no search over samples or layouts.
"""
from __future__ import annotations

import argparse
from collections import deque
import json
import math
from pathlib import Path
import random
import statistics

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "paper" / "figures"
SEED = 0
DECAY = 0.65
RADIUS = 2
VERTICES = 12


def dot(x: list[float], y: list[float]) -> float:
    return math.fsum(a * b for a, b in zip(x, y, strict=True))


def unit(x: list[float]) -> list[float]:
    norm = math.sqrt(dot(x, x))
    return [a / norm for a in x]


def sample() -> dict:
    """Two 6-cycles joined by a matching: a labelled simple cubic graph."""
    assert 0 <= DECAY < 1 / math.sqrt(2)
    edges = sorted({tuple(sorted((6 * layer + i, 6 * layer + (i + 1) % 6)))
                    for layer in range(2) for i in range(6)} | {(i, i + 6) for i in range(6)})
    neighbors = [[] for _ in range(VERTICES)]
    for u, v in edges:
        neighbors[u].append(v)
        neighbors[v].append(u)
    assert all(len(adj) == 3 for adj in neighbors)
    distances = []
    for v in range(VERTICES):
        dist = {v: 0}
        queue = deque([v])
        while queue:
            u = queue.popleft()
            for w in neighbors[u]:
                if w not in dist:
                    dist[w] = dist[u] + 1
                    queue.append(w)
        assert len(dist) == VERTICES
        distances.append([dist[z] for z in range(VERTICES)])
    rows = [unit([DECAY ** d if d <= RADIUS else 0.0 for d in row]) for row in distances]
    edge_rows = [unit([a + b for a, b in zip(rows[u], rows[v], strict=True)]) for u, v in edges]
    rng = random.Random(SEED)
    omega = [rng.gauss(0.0, 1.0) for _ in range(VERTICES)]
    scores = [dot(row, omega) for row in edge_rows]
    medians = [statistics.median(s for e, s in zip(edges, scores, strict=True) if v in e)
               for v in range(VERTICES)]
    order = sorted(range(VERTICES), key=lambda v: (medians[v], v))
    cuts = []
    for t in range(VERTICES + 1):
        prefix = set(order[:t])
        cuts.append([i for i, (u, v) in enumerate(edges) if (u in prefix) != (v in prefix)])
    widths = list(map(len, cuts))
    cut = widths.index(max(widths))

    # Check the normalization and median conditions in the construction.
    assert all(math.isclose(dot(row, row), 1.0, abs_tol=1e-12) for row in rows + edge_rows)
    for v, m in enumerate(medians):
        incident = [s for e, s in zip(edges, scores, strict=True) if v in e]
        assert sum(s <= m for s in incident) >= 2
        assert sum(m <= s for s in incident) >= 2
    assert sorted(order) == list(range(VERTICES))
    # Independently check the prefix cuts by the degree update, not by set membership.
    seen: set[int] = set()
    width = 0
    for t, v in enumerate(order, 1):
        width += 3 - 2 * sum(w in seen for w in neighbors[v])
        seen.add(v)
        assert widths[t] == width
    assert widths[0] == widths[-1] == 0
    return dict(graph="hexagonal prism", vertices=VERTICES, edges=edges, decay=DECAY,
                radius=RADIUS, seed=SEED, sampler="Python random.Random.gauss",
                omega=omega, scores=scores, medians=medians, order=order,
                cuts=cuts, widths=widths, highlighted_prefix=cut, cutwidth=max(widths))


def rounded(value):
    if isinstance(value, float):
        return round(value, 12)
    if isinstance(value, dict):
        return {k: rounded(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [rounded(v) for v in value]
    return value


def stats(data: dict) -> str:
    return ("% Generated by scripts/plot_gaussian_layout.py; do not edit.\n"
            rf"\newcommand{{\gaussianExampleCutwidth}}{{{data['cutwidth']}}}" + "\n"
            rf"\newcommand{{\gaussianExampleCut}}{{{data['highlighted_prefix']}}}" + "\n")


def check_data(actual, expected) -> None:
    """Exact combinatorics, with a small tolerance for platform-dependent libm rounding."""
    if isinstance(expected, float):
        assert math.isclose(actual, expected, rel_tol=0, abs_tol=2e-12), (actual, expected)
    elif isinstance(expected, dict):
        assert actual.keys() == expected.keys()
        for key in expected:
            check_data(actual[key], expected[key])
    elif isinstance(expected, list):
        assert len(actual) == len(expected)
        for a, b in zip(actual, expected, strict=True):
            check_data(a, b)
    else:
        assert actual == expected, (actual, expected)


def render(data: dict) -> None:
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib import pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap, Normalize
    from matplotlib.path import Path as PlotPath
    from matplotlib.patches import PathPatch

    blue, orange, gray = "#006699", "#c45713", "#a5a9ae"
    plt.rcParams.update({"font.family": "STIXGeneral", "font.size": 9,
                         "mathtext.fontset": "stix", "pdf.fonttype": 42,
                         "axes.spines.top": False, "axes.spines.right": False})
    score_fig = plt.figure(figsize=(6.5, 2.85))
    grid = score_fig.add_gridspec(1, 2, wspace=0.40, left=0.08, right=0.96, top=0.90, bottom=0.17)
    graph, median = score_fig.add_subplot(grid[0, 0]), score_fig.add_subplot(grid[0, 1])
    layout_fig = plt.figure(figsize=(6.5, 2.70))
    layout_grid = layout_fig.add_gridspec(2, 1, height_ratios=[0.75, 1], hspace=0.65,
                                        left=0.08, right=0.96, top=0.90, bottom=0.17)
    arcs, profile = layout_fig.add_subplot(layout_grid[0]), layout_fig.add_subplot(layout_grid[1])
    edges, scores, medians = data["edges"], data["scores"], data["medians"]
    order, cut, widths = data["order"], data["highlighted_prefix"], data["widths"]
    pos = {v: ((2.0 if v < 6 else 0.86) * math.cos(math.pi / 2 - 2 * math.pi * (v % 6) / 6),
               (2.0 if v < 6 else 0.86) * math.sin(math.pi / 2 - 2 * math.pi * (v % 6) / 6))
           for v in range(VERTICES)}
    cmap = LinearSegmentedColormap.from_list("edge_scores", [orange, "#b7bdc5", blue])
    scale = max(abs(s) for s in scores)
    norm = Normalize(-scale, scale)
    for (u, v), score in zip(edges, scores, strict=True):
        x, y = pos[u], pos[v]
        graph.plot([x[0], y[0]], [x[1], y[1]], color=cmap(norm(score)), lw=2.6, zorder=1)
        graph.text((x[0] + y[0]) / 2, (x[1] + y[1]) / 2, f"{score:.2f}",
                   ha="center", va="center", fontsize=7.8, zorder=3,
                   bbox=dict(facecolor="white", edgecolor="none", pad=0.9))
    for v, (x, y) in pos.items():
        graph.scatter([x], [y], s=155, c="white", edgecolors="#303840", linewidths=0.8, zorder=4)
        graph.text(x, y, str(v), ha="center", va="center", fontsize=8.5, zorder=5)
    graph.set(xlim=(-2.4, 2.4), ylim=(-2.35, 2.35), aspect="equal")
    graph.axis("off")
    graph.set_title("(a) Gaussian edge scores", loc="left", fontsize=10, pad=7)
    at_zero = [scores[i] for i, e in enumerate(edges) if 0 in e]
    graph.text(0.5, -0.08, "$m(0)=\\mathrm{med}\\{" + ",".join(f"{s:.2f}" for s in at_zero) +
               rf"\}}={medians[0]:.2f}$", transform=graph.transAxes, ha="center", fontsize=8)

    for i, v in enumerate(order):
        color = cmap(norm(medians[v]))
        median.plot([0, medians[v]], [i, i], color=gray, lw=0.8)
        median.scatter([medians[v]], [i], color=color, s=18, zorder=3)
        median.annotate(f"{medians[v]:.2f}", (medians[v], i), xytext=(5, 0),
                        textcoords="offset points", va="center", fontsize=7.8)
    median.axvline(0, color="#d0d0d0", lw=0.6, zorder=0)
    median.set(yticks=range(VERTICES), yticklabels=[str(v) for v in order],
               ylim=(VERTICES - 0.5, -0.5),
               xlim=(min(0, min(medians)) - 0.15, max(0, max(medians)) + 0.20),
               xlabel="median score $m(v)$", ylabel="vertex")
    median.tick_params(axis="both", length=2, labelsize=8)
    median.set_title("(b) Sort by the median", loc="left", fontsize=10, pad=7)

    rank = {v: i for i, v in enumerate(order)}
    highlighted = set(data["cuts"][cut])
    for i, (u, v) in enumerate(edges):
        a, b = sorted((rank[u], rank[v]))
        height = 0.27 + 0.19 * (b - a)
        path = PlotPath([(a, 0), (a, height), (b, height), (b, 0)],
                        [PlotPath.MOVETO, PlotPath.CURVE4, PlotPath.CURVE4, PlotPath.CURVE4])
        arcs.add_patch(PathPatch(path, fill=False, color=orange if i in highlighted else gray,
                                linewidth=1.7 if i in highlighted else 0.7,
                                zorder=2 if i in highlighted else 1))
    for i, v in enumerate(order):
        arcs.scatter([i], [0], s=160, c=blue if i < cut else "white", edgecolors=blue,
                     linewidths=0.8, zorder=4)
        arcs.text(i, 0, str(v), color="white" if i < cut else blue,
                  ha="center", va="center", fontsize=8.5, zorder=5)
    arcs.axvline(cut - 0.5, color=orange, ls=(0, (3, 2)), lw=1)
    arcs.text(cut - 0.38, 1.3, rf"$t={cut}$: {widths[cut]} crossing edges", color=orange,
              fontsize=8, ha="left", va="center")
    arcs.set(xlim=(-0.5, VERTICES - 0.5), ylim=(-0.4, 1.6))
    arcs.axis("off")
    arcs.set_title("(a) The induced layout and a widest frontier", loc="left", fontsize=10, pad=6)

    profile.plot(range(VERTICES + 1), widths, color=blue, marker="o", ms=3.5, lw=1.4)
    profile.axvline(cut, color=orange, lw=0.9, ls=(0, (3, 2)))
    profile.scatter([cut], [widths[cut]], color=orange, s=28, zorder=5)
    profile.axhline(data["cutwidth"], color=gray, lw=0.6, ls=(0, (3, 2)))
    profile.text(VERTICES - 0.1, data["cutwidth"] + 0.25, f"layout width = {data['cutwidth']}",
                 ha="right", fontsize=8.5)
    profile.set(xlim=(-0.15, VERTICES + 0.15), ylim=(-0.15, data["cutwidth"] + 1.0),
                xticks=range(VERTICES + 1), yticks=range(data["cutwidth"] + 1),
                xlabel="prefix length $t$", ylabel=r"$|\delta(P_t)|$")
    profile.tick_params(labelsize=8)
    profile.grid(axis="y", color="#e5e5e5", lw=0.5)
    profile.set_axisbelow(True)
    profile.set_title("(b) Every prefix cut", loc="left", fontsize=10, pad=7)
    for fig, name, title in [
        (score_fig, "gaussian-scores.pdf", "Gaussian edge scores and vertex medians"),
        (layout_fig, "gaussian-layout.pdf", "A Gaussian median layout of the hexagonal prism"),
    ]:
        fig.savefig(OUTPUT / name, metadata={"Creator": "plot_gaussian_layout.py",
                    "CreationDate": None, "ModDate": None, "Title": title})
        plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the committed numerical data, without plotting")
    args = parser.parse_args()
    data = sample()
    payload = json.dumps(rounded(data), indent=2) + "\n"
    if args.check:
        check_data(json.loads((OUTPUT / "gaussian-layout.json").read_text()), json.loads(payload))
        assert (OUTPUT / "gaussian-layout-stats.tex").read_text() == stats(data)
        print(f"Gaussian figure data checked: {VERTICES} vertices, {len(data['edges'])} edges, "
              f"cutwidth {data['cutwidth']}, highlighted prefix {data['highlighted_prefix']}.")
        return
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "gaussian-layout.json").write_text(payload)
    (OUTPUT / "gaussian-layout-stats.tex").write_text(stats(data))
    render(data)
    print(f"Wrote Gaussian layout figures; order {data['order']}, layout width {data['cutwidth']}.")


if __name__ == "__main__":
    main()
